export function getLayoutVariant(theme, questionIndex) {
  const config = sceneConfig[theme] || sceneConfig['legal-theory'];
  const variants = config.layoutVariants;
  return variants[questionIndex % variants.length];
}

export function getSceneConfig(theme) {
  return sceneConfig[theme] || sceneConfig['legal-theory'];
}

